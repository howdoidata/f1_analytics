-- FastF1 laps, typed to the Stage 2 column types. race_label and season come
-- from the extract folder (data/raw/fastf1/<season>/<race_label>/laps.csv).
-- Plain CAST, not TRY_CAST: a value of an unexpected type fails the build.
select
    regexp_extract(filename, '([^/\\]+)[/\\]([^/\\]+)[/\\][^/\\]+$', 2) as race_label,
    regexp_extract(filename, '([^/\\]+)[/\\]([^/\\]+)[/\\][^/\\]+$', 1) as season_folder,
    try_cast(season_folder as bigint) as season,
    "Time",
    "Driver",
    cast("DriverNumber" as bigint) as "DriverNumber",
    "LapTime",
    cast("LapNumber" as double) as "LapNumber",
    cast("Stint" as double) as "Stint",
    "PitOutTime",
    "PitInTime",
    "Sector1Time",
    "Sector2Time",
    "Sector3Time",
    "Sector1SessionTime",
    "Sector2SessionTime",
    "Sector3SessionTime",
    cast("SpeedI1" as double) as "SpeedI1",
    cast("SpeedI2" as double) as "SpeedI2",
    cast("SpeedFL" as double) as "SpeedFL",
    cast("SpeedST" as double) as "SpeedST",
    cast("IsPersonalBest" as boolean) as "IsPersonalBest",
    "Compound",
    cast("TyreLife" as double) as "TyreLife",
    cast("FreshTyre" as boolean) as "FreshTyre",
    "Team",
    "LapStartTime",
    cast("LapStartDate" as double) as "LapStartDate",
    cast("TrackStatus" as bigint) as "TrackStatus",
    cast("Position" as double) as "Position",
    cast("Deleted" as double) as "Deleted",
    cast("DeletedReason" as double) as "DeletedReason",
    cast("FastF1Generated" as boolean) as "FastF1Generated",
    cast("IsAccurate" as boolean) as "IsAccurate"
from {{ source('fastf1', 'laps') }}
